#!/usr/bin/env bash
#
# Copies the parts of aria this project needs into vendor/aria/, and records
# where they came from.
#
# After this, vendor/aria/ is OURS: it gets pruned and edited freely, and
# upstream is not followed. The manifest exists so an upstream fix can still be
# located and applied by hand.
#
#   wsl -d mscz_dev -- bash /mnt/c/.../scripts/vendor-aria.sh
#
# Re-running overwrites vendor/aria/, so local edits there are lost. That is
# intentional: use it to re-base onto a newer aria, then re-apply the prunes
# listed in VENDOR.md.

set -euo pipefail

ARIA_DIR="${ARIA_DIR:-/mnt/c/work/20260809/aria}"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${REPO_DIR}/vendor/aria"

if [ ! -d "${ARIA_DIR}/.git" ]; then
    echo "aria checkout not found at ${ARIA_DIR}" >&2
    exit 1
fi

# Only cheap git queries here. `git status` against a Windows checkout over
# /mnt/c takes minutes and reports every file as modified anyway, because the
# file mode differs across the 9p mount.
ARIA_COMMIT=$(git -C "${ARIA_DIR}" rev-parse HEAD)
ARIA_DESCRIBE=$(git -C "${ARIA_DIR}" describe --tags --always 2>/dev/null || echo "unknown")
ARIA_REMOTE=$(git -C "${ARIA_DIR}" remote get-url origin 2>/dev/null || echo "unknown")

echo "Vendoring from ${ARIA_DIR} @ ${ARIA_DESCRIBE}"
rm -rf "${DEST}"
mkdir -p "${DEST}"

copy() {
    local src="$1" dst="$2"
    shift 2
    local excludes=()
    local e
    for e in "$@"; do
        excludes+=(--exclude="$e")
    done
    mkdir -p "${DEST}/${dst}"
    rsync -a --delete "${excludes[@]}" "${ARIA_DIR}/${src}/" "${DEST}/${dst}/"
}

# engraving/tests is 33MB of test data. draw/thirdparty is the bundled FreeType
# 2.14.1 (22MB); the host build uses the system FreeType and the wasm build will
# use an emscripten port.
copy src/engraving        src/engraving        'tests/'
copy src/framework/global src/framework/global 'tests/'
copy src/framework/draw   src/framework/draw   'tests/' 'thirdparty/'
copy src/framework/cmake  src/framework/cmake
copy buildscripts/cmake   buildscripts/cmake
copy thirdparty           thirdparty

# global and engraving include interface headers from modules we do not build:
# the accessibility interfaces engraving's AccessibleItem derives from,
# iuiconfiguration and importexport/guitarpro/iguitarproconfiguration.h from
# EngravingConfiguration, iinteractiveprovider and imultiwindowsprovider from
# global's Settings and Interactive. Those headers include further ones
# (ui/uitypes.h wants workspace/workspacetypes.h, and so on), so rather than
# chase the chain, take every header from those trees. Headers only: no
# sources, nothing linked, and the build decides what it actually reads.
#
# Note the exclude order: rsync applies the first matching rule, so the
# directory excludes have to come before --include='*/' or they never fire.
headers_only() {
    rsync -a --delete --prune-empty-dirs \
        --exclude='thirdparty/' --exclude='tests/' \
        --exclude='global/' --exclude='draw/' --exclude='cmake/' \
        --include='*/' --include='*.h' --exclude='*' \
        "${ARIA_DIR}/$1/" "${DEST}/$1/"
}

headers_only src/framework
headers_only src/importexport

for f in SetupConfigure.cmake version.cmake; do
    cp "${ARIA_DIR}/${f}" "${DEST}/${f}"
done

# engraving.qrc reaches outside src/ for these three. The rest of aria's share/
# is 303MB of locale, soundfonts, templates and plugins that nothing here wants.
mkdir -p "${DEST}/share/instruments"
for f in instruments.xml orders.xml string_tunings_presets.json; do
    cp "${ARIA_DIR}/share/instruments/${f}" "${DEST}/share/instruments/${f}"
done

# Fonts: only what a default-style score needs.
#
# engraving's .qrc files embed 13 families, about 15MB, and they are the single
# biggest contributor to the eventual wasm payload. Keep Leland (the default
# music font), Edwin (the default text font), the SMuFL metadata, and the small
# special-purpose faces -- about 1.7MB. Left out, at about 14.5MB: Bravura,
# Petaluma, MScore, Gootville, MuseJazz, Finale Maestro, Finale Broadway, and
# the FreeSans/FreeSerif text fallbacks. The plan is to fetch those over HTTP on
# demand instead.
#
# Dropping them means editing the .qrc list and engravingmodule.cpp's font
# registration to match, including the Bravura default and fallback. Those edits
# are logged in VENDOR.md.
FONT_DIRS=(leland musejazz edwin smufl campania)
FONT_FILES=(mscore-BC.ttf mscoreTab.ttf fonts_figuredbass.xml fonts_tablature.xml README.md)

mkdir -p "${DEST}/fonts"
for d in "${FONT_DIRS[@]}"; do
    rsync -a --delete "${ARIA_DIR}/fonts/${d}/" "${DEST}/fonts/${d}/"
done
for f in "${FONT_FILES[@]}"; do
    cp "${ARIA_DIR}/fonts/${f}" "${DEST}/fonts/${f}"
done

cat >"${DEST}/VENDOR.md" <<EOF
# Vendored aria sources

Generated by \`scripts/vendor-aria.sh\`. Do not hand-edit this file; edit the
script and re-run it.

| | |
|---|---|
| Upstream | ${ARIA_REMOTE} |
| Commit | \`${ARIA_COMMIT}\` (HEAD of the checkout at copy time) |
| Describe | ${ARIA_DESCRIBE} |
| Copied | $(date -u +%Y-%m-%dT%H:%M:%SZ) |

aria's own engine provenance (which MuseScore release it derives from, and
aria's patches on top) is in that checkout's
\`sandbox/engraving/compat/ENGINE.md\`.

## Licensing

This tree is MuseScore-derived and is **GPL-3.0-only**. Keep the per-file
\`SPDX-License-Identifier: GPL-3.0-only\` / \`MuseScore-CLA-applies\` headers
intact; do not relicense these files.

## What was left out

| Excluded | Why |
|---|---|
| \`src/engraving/tests/\` | 33MB of test data |
| \`src/framework/{global,draw}/tests/\` | not used here |
| \`src/framework/draw/thirdparty/\` | bundled FreeType 2.14.1 (22MB); the host build uses the system FreeType and the wasm build will use an emscripten port |
| \`fonts/\` except Leland, MuseJazz, Edwin, SMuFL, Campania and the small special-purpose faces | Other music fonts and FreeSans/FreeSerif are omitted; jazz aliases use MuseJazz |
| \`buildscripts/{ci,packaging}/\` | not used here |
| \`src/importexport/\` except MusicXML import | Other importers and MusicXML export are omitted; the importer is copied directly from MuseScore v4.7.5 by \`scripts/vendor-musicxml.py\` (see its \`SOURCE.json\`) |
| \`sandbox/engraving/\` | aria's render core is one big translation unit that also pulls in FluidSynth, MIDI export and MusicXML. We write our own slim facade instead and port the display logic from it |

## Divergence from upstream

Record every deliberate change here as it is made, so the reason survives.

- Embed MuseJazz and MuseJazz Text with their metadata and OFL license. Current downloaded provenance is in fonts/musejazz/SOURCE.txt.
- Substitute Petaluma, Inkpen/Inkpen2, Reprise and Finale jazz families with MuseJazz; resolve text aliases in the Qt-free font database as well as Qt.
- Initialize the MuseJazz Qt resource explicitly, matching its QRC registration.
- Include rehearsal-mark alignment in the pre-4.7 style-position conversion, preserving legacy right alignment and avoiding extra collision-driven system spacing.
- Register legacy-style-defaults-v450.mss in engraving.qrc; DefaultStyle references this existing file, but MuseScore v4.7.5 omitted its resource alias.
EOF

echo
echo "Vendored into ${DEST}:"
du -sh "${DEST}"
du -sh "${DEST}"/*/ 2>/dev/null | sort -rh
