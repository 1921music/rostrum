#!/usr/bin/env python3
"""Turns Qt .qrc files into a plain alias-to-path manifest.

The engine asks for resources by the names the .qrc files give them --
":/engraving/instruments/instruments.xml" -- which are aliases, not where the
file sits in the tree (that one is share/instruments/instruments.xml). A Qt
build resolves those through the compiled-in resource table. Without Qt there
is no table, so the host needs the same mapping to find the file, and keeping
it generated means it cannot drift from the .qrc files.

    gen-resource-manifest.py --out manifest.txt <qrc> [<qrc>...]

Output is one "alias<TAB>path" line per entry, paths relative to the root the
manifest is loaded against, sorted.
"""

import argparse
import os
import sys
import xml.etree.ElementTree as ET


def entries(qrc_path, root):
    """Alias/path pairs from one .qrc, with paths made relative to `root`."""
    qrc_dir = os.path.dirname(os.path.abspath(qrc_path))
    tree = ET.parse(qrc_path)

    for resource in tree.getroot().findall("qresource"):
        prefix = (resource.get("prefix") or "").strip("/")
        for file_el in resource.findall("file"):
            target = (file_el.text or "").strip()
            if not target:
                continue

            alias = (file_el.get("alias") or target).strip()
            alias = "/".join(p for p in (prefix, alias) if p)

            real = os.path.normpath(os.path.join(qrc_dir, target))
            yield alias, os.path.relpath(real, root).replace(os.sep, "/")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True)
    parser.add_argument("--root", required=True,
                        help="paths in the manifest are relative to this")
    parser.add_argument("qrc", nargs="+")
    args = parser.parse_args()

    found = {}
    for qrc in args.qrc:
        if not os.path.exists(qrc):
            print(f"warning: no such .qrc: {qrc}", file=sys.stderr)
            continue
        for alias, real in entries(qrc, args.root):
            if alias in found and found[alias] != real:
                print(f"warning: {alias} maps to both {found[alias]} and {real}",
                      file=sys.stderr)
            found[alias] = real

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by scripts/gen-resource-manifest.py. Do not edit.\n")
        f.write("# alias<TAB>path, paths relative to the resource root.\n")
        for alias in sorted(found):
            f.write(f"{alias}\t{found[alias]}\n")

    print(f"{len(found)} entries -> {args.out}")


if __name__ == "__main__":
    main()
