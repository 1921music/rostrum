"""Embed a built score-engine web directory for offline/single-file Rostrum.

mise exec -- python build_score_engine.py --web <engine-build>/web
"""
import argparse
import base64
import gzip
import json
from pathlib import Path


def module(source):
    return 'data:text/javascript;base64,' + base64.b64encode(source.encode()).decode()


def pack(data):
    return base64.b64encode(gzip.compress(data, mtime=0)).decode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--web', type=Path, required=True)
    args = parser.parse_args()
    web = args.web.resolve()
    read = lambda name: (web / name).read_text(encoding='utf-8')
    wrapper = read('mscz.js').replace("'./mscz-engine.js'", repr(module(read('mscz-engine.js'))))
    wrapper = wrapper.replace("'./text-fonts.js'", repr(module(read('text-fonts.js'))))
    wrapper += '\nexport { Playback } from ' + repr(module(read('playback.js'))) + ';\n'
    worker = read('playback-worker.js').replace("import createSynth from './mscz-synth.js'",
        read('mscz-synth.js').replace('export default createSynth;', '').replace('import.meta.url', 'self.location.href'))
    resources = []
    for entry in json.loads(read('index.json'))['resources']:
        path = (web / entry['url']).resolve()
        path.relative_to(web)
        resources.append({'name': entry['name'], 'data': pack(path.read_bytes())})
    payload = {'module': pack(wrapper.encode()), 'wasm': pack((web / 'mscz-engine.wasm').read_bytes()),
        'resources': resources, 'playback': {'worker': pack(worker.encode()),
        'wasm': pack((web / 'mscz-synth.wasm').read_bytes())}}
    target = Path(__file__).parent / 'lib' / 'score-engine-data.js'
    target.write_text('// Generated by build_score_engine.py; GPL-3.0-only.\n'
        + 'globalThis._scoreEngineAssets_ = ' + json.dumps(payload, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{target}: {target.stat().st_size:,} bytes')


if __name__ == '__main__':
    main()
